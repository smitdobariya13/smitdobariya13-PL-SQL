SET SERVEROUTPUT ON;

BEGIN
	FOR REC IN(SELECT EID,ENAME,DEPTNO,DEPTNAME,GENDER,AGE,BASICSAL FROM EMP WHERE GENDER='M' AND DEPTNAME='HR')

LOOP
	DBMS_OUTPUT.PUT_LINE('EID:' ||REC.EID);
	DBMS_OUTPUT.PUT_LINE('ENAME:' ||REC.ENAME);
	DBMS_OUTPUT.PUT_LINE('DEPINO:' ||REC.DEPTNO);
	DBMS_OUTPUT.PUT_LINE('DNAME:' ||REC.DEPTNAME);
	DBMS_OUTPUT.PUT_LINE('GENDER:' ||REC.GENDER);
	DBMS_OUTPUT.PUT_LINE('AGES:' ||REC.AGE);
	DBMS_OUTPUT.PUT_LINE('BASICSAL:' ||REC.BASICSAL);
		END LOOP;
END;
