SET SERVEROUTPUT ON;

DECLARE
	ID EMP.EID%TYPE;
	NAME EMP.ENAME%TYPE;
	BS EMP.BASICSAL%TYPE;	
	DA NUMBER(10);
	HRA NUMBER(10);
	MEDICAL NUMBER(10);
	PF NUMBER(10);
	GS NUMBER(20);

BEGIN

	ID := &ID;

	SELECT EID,ENAME,BASICSAL
	INTO ID,NAME,BS
	FROM EMP
	WHERE ID = EID;

	DA :=(BS*50)/100;
	HRA := (BS*15)/100;
	MEDICAL :=500;
	PF :=(BS*10)/100;
	GS :=BS+(DA+HRA+MEDICAL)-PF;

	DBMS_OUTPUT.PUT_LINE('ENAME : '||NAME);
	DBMS_OUTPUT.PUT_LINE('GROSS SALARY : '||GS);

EXCEPTION
	WHEN NO_DATA_FOUND THEN
		DBMS_OUTPUT.PUT_LINE('')
END
/
